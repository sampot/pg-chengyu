const CLEAN = IDIOMS;

/** @type {Map<string, string[]>} */
const byFirst = new Map();
/** @type {Set<string>} */
const set = new Set(CLEAN);

for (const idiom of CLEAN) {
  const first = [...idiom][0];
  const list = byFirst.get(first);
  if (list) list.push(idiom);
  else byFirst.set(first, [idiom]);
}

export function allIdioms() {
  return CLEAN;
}

/** @param {string} s */
export function isIdiom(s) {
  return set.has(s.trim());
}

/**
 * @param {string} ch
 * @param {Set<string>} used
 */
export function startersWith(ch, used) {
  const list = byFirst.get(ch) || [];
  return list.filter((x) => !used.has(x));
}

/** @param {string} idiom */
export function lastChar(idiom) {
  const chars = [...idiom];
  return chars[chars.length - 1] || "";
}

/** @param {string} idiom */
export function firstChar(idiom) {
  return [...idiom][0] || "";
}

/** @param {number} [minOut] */
export function pickSeed(minOut = 2) {
  const pool = CLEAN.filter((id) => startersWith(lastChar(id), new Set([id])).length >= minOut);
  const list = pool.length ? pool : [...CLEAN];
  return list[Math.floor(Math.random() * list.length)];
}

/**
 * @param {string} needFirst
 * @param {Set<string>} used
 * @param {number} [count]
 */
export function buildChoices(needFirst, used, count = 4) {
  const valid = startersWith(needFirst, used);
  /** @type {string[]} */
  const picks = [];
  const validShuf = shuffle(valid);
  const takeValid = Math.min(validShuf.length, Math.max(1, Math.min(2, count - 1)));
  for (let i = 0; i < takeValid; i++) picks.push(validShuf[i]);

  const distractors = shuffle(
    CLEAN.filter((x) => !used.has(x) && firstChar(x) !== needFirst && !picks.includes(x)),
  );
  while (picks.length < count && distractors.length) {
    picks.push(/** @type {string} */ (distractors.pop()));
  }
  const rest = shuffle(CLEAN.filter((x) => !used.has(x) && !picks.includes(x)));
  while (picks.length < count && rest.length) picks.push(/** @type {string} */ (rest.pop()));
  return shuffle(picks);
}

/**
 * @template T
 * @param {T[]} arr
 */
function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
